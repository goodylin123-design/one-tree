function update(
  treeId: string,
  season: string,
  takenOn: string,
  status: TreeUpdate['status'],
  species: string,
  note: string,
  height: number,
  photo: string,
): TreeUpdate {
  return {
    id: nid('upd'),
    treeId,
    season,
    takenOn,
    photos: [{ url: photo, kind: 'full' }],
    heightCm: height,
    status,
    species,
    note,
    uploader: '示例',
    sample: true,
    createdAt: `${takenOn}T08:00:00.000Z`,
  }
}

